import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve,sep} from 'node:path';
import {birthdayDate,birthdayEntries,birthdayEvents,nextBirthday,daysUntil} from '../public/domain.js';

test('Geburtstage wiederholen sich jährlich, behalten unbekannte Geburtsjahre und behandeln Schaltjahre',()=>{
 const b={id:'b',name:'Anna',month:1,day:3,year:1995,personId:'anna',note:''};
 assert.equal(nextBirthday(b,'2026-12-30'),'2027-01-03');
 assert.equal(nextBirthday(b,'2027-01-03'),'2027-01-03');
 assert.equal(nextBirthday(b,'2027-01-04'),'2028-01-03');
 assert.equal(birthdayDate(b,1990),null);
 assert.equal(daysUntil('2027-01-03','2026-12-30'),4);
 assert.equal(daysUntil('2026-03-30','2026-03-28'),2,'Tagesabstand unabhängig von der Zeitumstellung');
 const leap={...b,month:2,day:29,year:null};
 assert.equal(birthdayDate(leap,2027),null);
 assert.equal(nextBirthday(leap,'2026-11-19'),'2028-02-29');
 const events=birthdayEvents([b],2027);
 assert.equal(events[0].date,'2027-01-03');assert.equal(events[0].personId,'anna');assert.equal(events[0].birthdayId,'b');
 const legacy={id:'event1',title:'Omas Geburtstag',date:'2020-10-20',category:'Geburtstag',personId:null,note:'Blumen'};
 const entries=birthdayEntries([b],[legacy,{...legacy,id:'normal',category:'Alltag'}]);
 assert.equal(entries.length,2);assert.equal(entries[1].legacyEventId,'event1');assert.equal(entries[1].year,null);
 assert.equal(birthdayEvents(entries,2027).find(e=>e.legacyEventId==='event1').date,'2027-10-20');
});

