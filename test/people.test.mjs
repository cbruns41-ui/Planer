 assert.equal((await request('/api/birthdays','POST',{name:'Oma Erika',month:2,day:29,year:'',note:''},owner.cookie)).status,201,'29. Februar ohne Geburtsjahr ist möglich');
 const guest=await request('/api/auth/register','POST',{name:'Gast',email:'people-guest@example.test',password:'DasIstEinLangesPasswort',invite:owner.data.space.invite});
 const other=await request('/api/auth/register','POST',{name:'Andere',email:'people-other@example.test',password:'DasIstEinLangesPasswort'});
 assert.equal((await request('/api/calendar','GET',undefined,guest.cookie)).data.birthdays.length,2);
 assert.equal((await request('/api/calendar','GET',undefined,other.cookie)).data.birthdays.length,0);
